#!/usr/bin/env python3
"""Generate the specs/README.md index and specs/epic-mapping.json from spec.yaml files.

Both outputs are derived, never hand-edited: the index is the human view and the
epic mapping is the machine view (consumed by create_jira_from_spec.py and by the
O7 Weekly Delivery Synthesis report, which joins tickets to components on the epic key).

Usage:
    python3 scripts/generate_spec_index.py
"""

import json
from pathlib import Path

import yaml

from spec_paths import SPECS_DIR, iter_spec_dirs

VALID_GATES = ["D0", "D1", "D2", "D3", "D4", "done"]

# Rendered in this order; the label is the section heading in the index.
SPEC_TYPES = {
    "onboarding": "Onboarding — business-group use cases onto ACP",
    "integration": "Integration — connecting existing systems to ACP",
    "platform": "Platform — ACP product capabilities",
    "pattern": "Pattern — reusable architecture patterns for EA approval",
    "governance": "Governance — risk and compliance scope",
}


def resolve_gate(c: dict) -> str:
    """Gate from current_gate, tolerating the older specs that put it in status."""
    for key in ("current_gate", "status"):
        value = str(c.get(key, "") or "")
        if value in VALID_GATES:
            return value
    return "?"


def main():
    specs_dir = Path("specs")
    if not specs_dir.exists():
        print("ERROR: specs/ directory not found")
        return

    components = []
    for spec_dir in iter_spec_dirs(SPECS_DIR):
        with open(spec_dir / "spec.yaml") as f:
            data = yaml.safe_load(f)
        # <spec_type>/<component>, relative to specs/ — what the index links to.
        data["_path"] = spec_dir.relative_to(SPECS_DIR).as_posix()
        components.append(data)

    # Build the index markdown
    lines = [
        "# ACP Specs — Component Index",
        "",
        "> Auto-generated by `scripts/generate_spec_index.py`. Do not edit manually.",
        "",
        "## Status Dashboard",
        "",
        "| Component | Type | Gate | Status | Epic | Owner | Repo |",
        "|-----------|------|------|--------|------|-------|------|",
    ]

    gate_counts = {g: 0 for g in VALID_GATES}
    type_counts = {t: 0 for t in SPEC_TYPES}

    for c in components:
        gate = resolve_gate(c)
        spec_type = c.get("spec_type", "—")
        status = c.get("status", "draft")
        epic = c.get("jira_epic", "—")
        owner = c.get("owner", "TBD")
        repo = c.get("repo", "—")
        title = c.get("title", c.get("component", "?"))
        component = c.get("component", "?")

        gate_counts[gate] = gate_counts.get(gate, 0) + 1
        type_counts[spec_type] = type_counts.get(spec_type, 0) + 1

        lines.append(
            f"| [{title}]({c['_path']}/) | {spec_type} | {gate} | {status} | {epic} | {owner} | {repo} |"
        )

    lines.extend([
        "",
        "## Progress",
        "",
        f"- **D0 Discovery**: {gate_counts.get('D0', 0)} components",
        f"- **D1 Requirements**: {gate_counts.get('D1', 0)} components",
        f"- **D2 Design**: {gate_counts.get('D2', 0)} components",
        f"- **D3 Tasks**: {gate_counts.get('D3', 0)} components",
        f"- **D4 Verification**: {gate_counts.get('D4', 0)} components",
        f"- **Done**: {gate_counts.get('done', 0)} components",
        "",
        "## By type",
        "",
    ])
    for spec_type, label in SPEC_TYPES.items():
        lines.append(f"- **{label}**: {type_counts.get(spec_type, 0)} components")
    lines.extend(["", "## Component Specs", ""])

    by_type: dict[str, list[dict]] = {}
    for c in components:
        by_type.setdefault(c.get("spec_type", "—"), []).append(c)

    ordered_types = list(SPEC_TYPES) + [t for t in sorted(by_type) if t not in SPEC_TYPES]
    for spec_type in ordered_types:
        group = by_type.get(spec_type)
        if not group:
            continue
        lines.extend([f"### {SPEC_TYPES.get(spec_type, spec_type)}", ""])
        for c in group:
            component = c.get("component", "?")
            title = c.get("title", component)
            desc = c.get("description", "")
            epic = c.get("jira_epic", "")
            gate = resolve_gate(c)

            lines.append(f"#### [{title}]({c['_path']}/)")
            if epic:
                lines.append(f"**Epic**: {epic} | **Gate**: {gate} | **Type**: {spec_type}")
            lines.append("")
            if desc:
                lines.append(desc)
            lines.append("")

            spec_dir = specs_dir / c["_path"]
            for gate_file in sorted(spec_dir.glob("d*.md")):
                lines.append(f"- [{gate_file.name}]({c['_path']}/{gate_file.name})")
            lines.append("")

    output = Path("specs/README.md")
    output.write_text("\n".join(lines))
    print(f"Generated {output} with {len(components)} components")

    write_epic_mapping(components)


def write_epic_mapping(components: list[dict]) -> None:
    """Rebuild specs/epic-mapping.json (schema kept for create_jira_from_spec.py)."""
    mapping_path = Path("specs/epic-mapping.json")
    existing = {}
    if mapping_path.exists():
        for entry in json.loads(mapping_path.read_text()):
            if isinstance(entry, dict) and entry.get("component"):
                existing[entry["component"]] = entry

    mapping = []
    for c in components:
        component = c.get("component", "?")
        mapping.append({
            "component": component,
            "title": c.get("title", component),
            "card_id": existing.get(component, {}).get("card_id", ""),
            "jira_key": c.get("jira_epic", ""),
            "spec_dir": c["_path"],
            "spec_type": c.get("spec_type", ""),
            "current_gate": resolve_gate(c),
        })

    mapping_path.write_text(json.dumps(mapping, indent=2) + "\n")
    dropped = sorted(set(existing) - {m["component"] for m in mapping})
    missing_epic = [m["component"] for m in mapping if not m["jira_key"]]
    print(f"Generated {mapping_path} with {len(mapping)} components")
    if dropped:
        print(f"  dropped stale entries with no spec dir: {', '.join(dropped)}")
    if missing_epic:
        print(f"  WARNING: no jira_epic for: {', '.join(missing_epic)}")


if __name__ == "__main__":
    main()
